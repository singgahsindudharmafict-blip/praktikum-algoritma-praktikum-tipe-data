# Activity 2 – Konversi Tipe Data

# Percobaan A – Float ke Integer
nilai = 87.75

print(nilai)
print(type(nilai))

nilai_baru = int(nilai)

print(nilai_baru)
print(type(nilai_baru))


# Percobaan B – Integer ke String
skor = 90
skor_teks = str(skor)

print("Nilai saya adalah " + skor_teks)
print(type(skor_teks))


# Percobaan C – String ke Float
berat = "65.5"
berat_baru = float(berat)

print(berat_baru)
print(type(berat_baru))
print(berat_baru + 2.5)
